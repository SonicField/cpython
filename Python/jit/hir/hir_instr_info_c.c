#define HIR_INSTR_INFO_COUNT \
    (sizeof(hir_instr_info_table) / sizeof(hir_instr_info_table[0]))

const HirInstrInfo *hir_instr_get_info(int opcode) {
    if (opcode < 0 || (size_t)opcode >= HIR_INSTR_INFO_COUNT) {
        return &hir_instr_info_table[0]; /* fallback to Assign */
    }
    return &hir_instr_info_table[opcode];
}
